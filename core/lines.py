"""OCR 줄 -> 약 이름 후보만 남긴다.

약봉투에는 약 이름이 아닌 글자가 훨씬 많다. 조제일자, 용법, 약국명,
전화번호. 이걸 그대로 매칭에 넣으면 "식후"가 "후라시닐정"에 60%로
붙는다. 퍼지 검색이 짧은 문자열에 부분일치 보너스를 주기 때문이다.

그 결과가 위험하다. 사람에게 보여줄 후보 목록이 잡음으로 덮이고,
사용자가 그중 하나를 고르면 먹지도 않은 약이 확정되어 판정 엔진에
들어간다. 미탐보다 이쪽이 나쁘다.

거르는 방법은 두 단계다.
  1) 날짜·용법·용량·안내 문구를 줄에서 걷어낸다.
  2) 걷어내고 남은 글자가 약 이름이 되기에 너무 짧으면 버린다.

"지우고 남은 것으로 판단"하는 순서가 중요하다. "숫자가 있으면 버린다"로
하면 타이레놀8시간이알서방정 같은 실제 품목명이 같이 죽는다.

규칙은 전부 결정론적이다. 학습도 LLM도 쓰지 않는다. 한 봉투 양식에
맞추지 않고, 양식이 달라도 성립하는 것만 넣는다.
"""
from __future__ import annotations

import re

# 약 이름이 되려면 최소 이만큼은 남아야 한다.
# 국내 품목명 중 한글 2자짜리는 사실상 없다. 3자가 하한이다(탁센, 훼스탈).
MIN_KOR = 3

# 이 말이 한 번이라도 보이면 그 줄은 통째로 버린다.
# 기관명·사람 이름은 일부만 지우면 "서울대약국"이 "서울대"로 남아
# 다시 약 이름 행세를 한다. 품목명에는 절대 나오지 않는 말들이다.
_KILL = re.compile(
    r"(약국|병원|의원|한의원|치과|보건소|의료원|클리닉|약사|의사|면허|"
    r"전화|TEL|Tel|tel|팩스|FAX|\d{2,4}\s*-\s*\d{3,4}\s*-\s*\d{4}|"
    r"조제일자|조제일|조제자|조제|처방전|처방일|처방|투약일|투약|교부|"
    r"복약지도|복약|용법|용량|주의사항|환자|성명|생년월일|"
    r"총\s*\d*\s*종|약제비|본인부담|"
    # 실물 약봉투 5장에서 필터를 통과해 none 으로 떨어진 줄을 보고 추가한 것.
    # 전부 약국 인쇄물의 일반 관행이라 특정 봉투에 맞춘 게 아니다.
    r"약효|"                                              # "-약효 천식COPD포함/비염약"
    r"(?:하|드|주)세요|(?:하|드)십시오|"                    # 복약 안내 문장의 어미. 약 이름은 이렇게 안 끝난다
    r"상의하|주의하|섭취하|병용하|투여하|개선없|운전|기계조작|"  # 복약 안내 문장의 동사구
    r"보관\s*$|"                                          # 실온보관 / 차광보관 / 냉장보관
    r"[가-힣]색\s*(?:정제|정|캡슐|캅셀)\s*$|"               # 흰색정제 / 청색정제 — 외형 설명
    # 약국 영수증·수납 내역의 필드명. 약봉투 대신 영수증 겸 복약안내문을
    # 한 장으로 주는 약국이 있고, 그러면 이 줄들이 전부 매칭에 들어간다.
    # 카탈로그 65,995건 중 이 패턴에 걸리는 품목명은 0건이다.
    # "수가" 를 넣었다가 "한국특수가스의료용산소" 가 죽어서 뺐다.
    r"영수증|영수중|승인번호|등록번호|사업자|소득공제|수납|보험자|급여|급예|"
    r"부담금|금액|발행일|내방일|소재지|청구)")

# 뺀 말들: 일수, 나이, 성별, 수량, 매수, 합계.
# 품목명 안에 그대로 들어있다. "리세드론산나트륨일수화물"의 "일수",
# "나이트로글리세린"의 "나이". 한 번이라도 걸리면 진짜 약이 통째로 사라진다.
# 짧은 잡음 조각은 match.py 의 길이 가드가 막으므로 여기서 욕심낼 이유가 없다.

# 줄에서 걷어내는 것들. 걷어내고 남은 부분이 약 이름 후보가 된다.
_SUB = [
    # 날짜. 2026-09-07 / 2026.9.7 / 26년 9월 7일
    re.compile(r"\d{2,4}\s*[-./년]\s*\d{1,2}\s*[-./월]\s*\d{1,2}\s*일?"),
    # 복용 빈도·시간. 1일3회, 3포, 30분, 8시간, 5일분.
    # 함량(500mg, 10밀리그램)은 일부러 남긴다. 같은 이름 다른 용량이
    # 서로 다른 품목이라, 지우면 매칭이 후보를 좁히지 못한다.
    # "시간" 을 뺐다. 타스펜8시간이알서방정650밀리그람 처럼 제품명에 들어가는 약이 실재하고,
    # 떼면 매칭 점수가 auto 에서 suggest(0.72) 로 떨어진다. 실물 약봉투에서 걸렸다.
    # "8시간마다" 같은 진짜 용법은 뒤의 "마다"·"간격" 이 있어야 성립하므로 그것만 잡는다.
    re.compile(r"\d+\s*(일분|일치|일|회|번|포|매|팩|앰플|분)"),
    re.compile(r"\d+\s*시간\s*(?:마다|간격|간)"),
    # 복용 시점
    re.compile(r"(식전|식후|식간|취침\s*전|취침|아침|점심|저녁|자기\s*전|공복|하루|매일)"),
]

# 설명 문장의 머리글 기호. 약국 인쇄물은 약효·주의사항을 불릿으로 단다.
#   -혈관확장및수분재흡수억제작용으로
#   -코피멍생리과다지속되면전문가와
# 품목명이 이 기호로 시작하는 경우는 카탈로그 65,995건 중 0건이다.
_BULLET = re.compile(r"^\s*[-·•※*]")

# 제형 토큰. 아래 약효분류 판정에서 "제" 로 끝나는 진짜 품목명을 지키는 데 쓴다.
# 경고제·관류제·트로키제·이식제·아가아제는 분류명이 아니라 제형이다.
_FORM_TOKEN = re.compile(
    r"정|캡슐|캅셀|시럽|산|주|액|환|과립|패취|크림|연고|겔|점안|흡입|좌|짜|첩|건조|분말"
    r"|경고제|관류제|트로키제|아가아제|이식제")
_ONLY_KOR = re.compile(r"^[가-힣\s]+$")
# 약효분류 라벨의 최소 길이. 4 로 하면 "헌터라제" 가 죽는다. 실재하는 품목이다.
MIN_CLASS = 5


def _is_class_label(s: str) -> bool:
    """혈압강하제 / 항혈소판제 / 위장운동촉진제 같은 약효분류 라벨인가.

    약국 인쇄물이 약 이름 바로 아래 한 줄로 붙인다. 매칭에 넣으면
    "항혈소판제" 가 "대한적십자사서울중앙혈액원농축혈소판" 에 0.68 로 붙어
    확인 화면에 수혈용 혈액제제가 후보로 올라온다.

    조건 셋을 다 만족해야 한다. 순한글이고, MIN_CLASS 자 이상이고,
    "제" 로 끝나는데 제형 토큰이 없다. 카탈로그 65,995건과 그 괄호 앞
    짧은 이름까지 통과시켜서 죽는 품목명이 0건인 것을 확인했다.
    """
    s = s.strip()
    return (bool(_ONLY_KOR.match(s)) and len(s) >= MIN_CLASS
            and s.endswith("제") and not _FORM_TOKEN.search(s))


_TAIL = re.compile(r"[\s/.,\-+_]+$")
_KOR = re.compile(r"[가-힣]")
# OCR이 흘린 기호. 약 이름에 남을 이유가 없다.
_TRASH = re.compile(r"[^\w가-힣()\[\]/.\-+]")


def core_text(line: str) -> str:
    """줄에서 날짜·용법을 걷어내고 남은 부분.

    원래 줄에 띄어쓰기가 없었으면 지운 자리도 붙여서 되돌린다.
    타이레놀8시간이알서방정 -> 타이레놀이알서방정. 여기를 띄우면
    한 품목명이 두 조각이 되어 매칭 점수가 떨어진다.
    """
    glue = "" if not re.search(r"\s", line.strip()) else " "
    s = line
    for pat in _SUB:
        s = pat.sub(glue, s)
    s = _TRASH.sub(" ", s)
    s = " ".join(s.split()) if glue else s.strip()
    # 지우고 남은 꼬리 기호. "아모잘탄정5/50mg"에서 함량만 빠졌을 때의 "5/" 같은 것.
    return _TAIL.sub("", s)


def clean(line: str) -> str | None:
    """약 이름 후보를 돌려준다. 후보가 아니면 None.

    한 줄에 이름과 용법이 섞여 있으면(페니라민정 1일3회 식후) 이름만 남긴다.
    """
    if not line or not line.strip():
        return None
    if _KILL.search(line) or _BULLET.match(line) or _is_class_label(line):
        return None
    s = core_text(line)
    if len(_KOR.findall(s)) < MIN_KOR:
        return None
    return s


def filter_lines(lines: list[str]) -> tuple[list[str], int]:
    """줄 목록 -> (약 이름 후보 목록, 버린 줄 수).

    중복은 남긴다. 같은 약이 두 번 적힌 봉투가 실제로 있고,
    그 판단은 사람이 확인 화면에서 한다.
    """
    kept, dropped = [], 0
    for line in lines:
        c = clean(line)
        if c is None:
            dropped += 1
            continue
        kept.append(c)
    return kept, dropped
