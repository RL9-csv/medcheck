def test_약효분류_규칙이_짧은_이름과_제형을_안_건드린다():
    """"제" 로 끝난다고 다 분류명이 아니다.

    헌터라제는 순한글 4자이고, 경고제·관류제·트로키제·이식제는 제형이다.
    분류명 규칙은 순한글 5자 이상 + 제형 토큰 없음일 때만 성립한다.
    """
    for name in ("헌터라제", "고닐고포르테경고제", "네오로닌관류제",
                 "뮤코안진트로키제", "임플라논엔엑스티이식제"):
        assert clean(name) is not None, f"품목명을 죽였다: {name!r}"


def test_이름_안의_글자를_영수증_필드로_착각하지_않는다():
    """"한국특수가스의료용산소" 의 "수가".

    영수증 토큰에 "수가" 를 넣었다가 카탈로그 전수 검사에서 잡혔다.
    한 건이라도 죽으면 그 규칙은 쓰지 않는다.
    """
    assert clean("한국특수가스의료용산소") is not None
