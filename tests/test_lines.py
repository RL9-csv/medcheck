"""줄 필터가 지켜야 하는 두 가지.

  버려야 할 것을 버린다  — 조제일자, 용법, 기관명
  남겨야 할 것을 남긴다  — 실제 품목명. 이쪽 실패가 훨씬 위험하다.

두 번째가 이 파일의 존재 이유다. 필터가 과해져서 진짜 약 이름을 지우면
사용자는 자기가 먹는 약이 목록에서 사라진 것을 알아채지 못한다.
버리는 규칙을 추가할 때마다 아래 KEEP 목록이 전부 살아있는지 본다.
"""
import pytest

from core.lines import clean, filter_lines, core_text

# 실제 약봉투에 찍히는 비-약품 줄. 전부 버려야 한다.
DROP = [
    "조제일자", "조제일자 2026-09-07", "2026-09-07", "2026.09.07",
    "1일", "2회", "1일3회", "1일 2회 식후 30분", "30분", "식후", "식전",
    "취침 전", "아침", "총3종", "총 3 종", "5일분",
    "내과", "의원", "약사", "행복내과의원", "서울대약국 02-880-1234",
    "환자 성명 홍길동", "생년월일", "복약지도", "본인부담금",
    "500mg 1일3회", "", "   ", "Y능", "O02",
]

# 식약처 품목명에 실제로 있는 형태. 전부 살아야 한다.
KEEP = [
    "페니라민정", "아펜탈정", "훼스탈", "미니보라30",
    "에어탈정(아세클로페낙)", "타이레놀8시간이알서방정",
    "아모잘탄정5/50mg", "크레스토정10밀리그램", "제일아미노필린주사액",
    "판베시서방캡슐 30밀리그램(펜터민염산염)",
    # 벤치마크에서 실제로 필터가 죽였던 이름들. 재발 방지용으로 박아둔다.
    "리도넬정35밀리그램(리세드론산나트륨일수화물)",
    "나이트로글리세린설하정",
    "타스펜8시간이알서방정650밀리그람",     # 실물 약봉투에서 걸린 것
    "일성세프트리악손주2그램(세프트리악손나트륨수화물)",
    # 영수증/약효분류 규칙을 넣을 때 카탈로그 전수 검사에서 걸렸던 이름들.
    "한국특수가스의료용산소",          # "수가" 를 영수증 토큰에 넣었다가 죽였다
    "헌터라제",                       # 순한글 4자 + "제" 로 끝난다. 약효분류가 아니다
    "고닐고포르테경고제", "네오로닌관류제", "뮤코안진트로키제",
    "임플라논엔엑스티이식제",          # 경고제/관류제/트로키제/이식제는 제형이다
]


@pytest.mark.parametrize("line", DROP)
def test_drop(line):
    assert clean(line) is None, f"버려야 하는데 남았다: {line!r}"


@pytest.mark.parametrize("line", KEEP)
def test_keep(line):
    assert clean(line) is not None, f"남겨야 하는데 버렸다: {line!r}"


def test_함량은_지우지_않는다():
    """같은 이름 다른 용량은 서로 다른 품목이다. 지우면 후보를 좁힐 수 없다."""
    assert "10" in clean("크레스토정10밀리그램")
    assert "50" in clean("아모잘탄정5/50mg")


def test_한_줄에_이름과_용법이_섞이면_이름만_남는다():
    assert clean("페니라민정 1일3회 식후") == "페니라민정"
    assert clean("알마겔정 3포") == "알마겔정"


def test_원래_붙어있던_이름은_붙여서_되돌린다():
    """지운 자리를 띄우면 한 품목명이 두 조각이 되어 매칭 점수가 떨어진다."""
    assert clean("타이레놀정500밀리그람 1일3회") == "타이레놀정500밀리그람"


def test_OCR이_깨뜨린_약이름은_버리지_않는다():
    """매칭이 복구할 몫이다. 여기서 버리면 복구할 기회 자체가 없다."""
    assert clean("공어눔은") is not None
    assert clean("에어탈젓") is not None


def test_filter_lines가_버린_개수를_센다():
    kept, dropped = filter_lines(["조제일자", "페니라민정", "1일3회", "에어탈정"])
    assert kept == ["페니라민정", "에어탈정"]
    assert dropped == 2


def test_같은_약이_두_번_적혀도_지우지_않는다():
    """중복 판단은 사람이 확인 화면에서 한다."""
    kept, _ = filter_lines(["페니라민정", "페니라민정"])
    assert len(kept) == 2


def test_염_이름_안의_글자를_안내문구로_착각하지_않는다():
    """"나트륨일수화물"의 "일수", "나이트로"의 "나이".

    이 두 글자를 안내문구로 보고 줄 전체를 버렸다가 벤치마크에서 잡혔다.
    한 번이라도 걸리면 사용자가 먹는 약이 목록에서 통째로 사라진다.
    짧은 잡음은 match.py 의 길이 가드가 막으므로 여기서 욕심낼 이유가 없다.
    """
    assert clean("리세드론산나트륨일수화물") is not None
    assert clean("나이트로글리세린설하정") is not None


def test_제품명에_들어간_시간은_떼지_않는다():
    """타스펜8시간이알서방정650밀리그람 은 "8시간" 이 이름의 일부다.

    용법으로 보고 떼면 매칭이 auto 에서 suggest(0.72) 로 떨어진다. 실물 약봉투에서
    걸렸다. 진짜 용법은 "8시간마다", "12시간 간격" 처럼 뒤에 말이 붙는다.
    """
    assert clean("타스펜8시간이알서방정650밀리그람") == "타스펜8시간이알서방정650밀리그람"
    assert clean("타이레놀8시간이알서방정") == "타이레놀8시간이알서방정"
    assert clean("8시간마다") is None
    assert clean("12시간 간격") is None


